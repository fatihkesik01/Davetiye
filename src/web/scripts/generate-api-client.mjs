import { readFile, writeFile } from 'node:fs/promises'

const scriptDirectory = new URL('.', import.meta.url)
const specUrl = new URL('../openapi/davetiye.v1.json', scriptDirectory)
const outputUrl = new URL('../src/api/generated/client.ts', scriptDirectory)

async function downloadOpenApiDocument() {
  const endpoint = process.env.DAVETIYE_OPENAPI_URL
  if (!endpoint) {
    throw new Error('DAVETIYE_OPENAPI_URL must point to the running API OpenAPI document.')
  }

  const response = await fetch(endpoint)
  if (!response.ok) {
    throw new Error(`Could not download OpenAPI document: ${response.status}.`)
  }

  return `${JSON.stringify(await response.json(), null, 2)}\n`
}

if (process.argv.includes('--sync')) {
  await writeFile(specUrl, await downloadOpenApiDocument())
}

const specText = await readFile(specUrl, 'utf8')
if (process.argv.includes('--verify')) {
  const downloaded = await downloadOpenApiDocument()
  if (specText !== downloaded) {
    throw new Error('OpenAPI snapshot is stale. Run npm run api:sync against the API under test.')
  }
}

const spec = JSON.parse(specText)
const operation = spec.paths?.['/api/v1/system/info']?.get
const sessionOperation = spec.paths?.['/api/v1/auth/session']?.get

if (!String(spec.openapi).startsWith('3.1.') || !operation || !sessionOperation) {
  throw new Error('OpenAPI snapshot does not satisfy the Phase 1 client contract.')
}

const output = `// <auto-generated />\n// Source: openapi/davetiye.v1.json. Do not edit by hand; run npm run api:generate.\n\nexport interface SystemInfo {\n  service: string\n  apiVersion: string\n}\n\nexport type SessionAccess = 'creator' | 'mfa-complete-super-admin' | 'none'\n\nexport interface SessionAccessSnapshot {\n  authenticated: boolean\n  access: SessionAccess\n}\n\nexport interface ApiClientOptions {\n  baseUrl?: string\n  fetch?: typeof globalThis.fetch\n}\n\nexport class DavetiyeApiClient {\n  private readonly baseUrl: string\n  private readonly request: typeof globalThis.fetch\n\n  public constructor(options: ApiClientOptions = {}) {\n    this.baseUrl = (options.baseUrl ?? '').replace(/\\/$/, '')\n    this.request = options.fetch ?? globalThis.fetch\n  }\n\n  public async getSystemInfo(signal?: AbortSignal): Promise<SystemInfo> {\n    const response = await this.request(\`${'${this.baseUrl}'}/api/v1/system/info\`, {\n      credentials: 'include',\n      signal,\n    })\n\n    if (!response.ok) {\n      throw new Error(\`API request failed with status ${'${response.status}'}.\`)\n    }\n\n    return (await response.json()) as SystemInfo\n  }\n\n  public async getSessionAccess(signal?: AbortSignal): Promise<SessionAccessSnapshot> {\n    const response = await this.request(\`${'${this.baseUrl}'}/api/v1/auth/session\`, {\n      credentials: 'include',\n      cache: 'no-store',\n      signal,\n    })\n\n    if (!response.ok) {\n      throw new Error(\`API request failed with status ${'${response.status}'}.\`)\n    }\n\n    return (await response.json()) as SessionAccessSnapshot\n  }\n}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(outputUrl, 'utf8')
  if (current !== output) {
    throw new Error('Generated API client is stale. Run npm run api:generate.')
  }
} else {
  await writeFile(outputUrl, output)
}
